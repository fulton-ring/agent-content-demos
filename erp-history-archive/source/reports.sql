-- Source-side reports, run in SQL Server against the live GP database.
-- They read the tables GP's own reports read: the trial balance comes from the
-- account summary tables (GL10110, GL10111), the agings from the open and history
-- documents and their applications. Each report starts with "-- name: <report>".
-- :asof_last is replaced with the last date of data before running.

-- name: trial_balance
WITH summ AS (
  SELECT ACTINDX, YEAR1, PERIODID, DEBITAMT, CRDTAMNT, PERDBLNC FROM GL10110
  UNION ALL
  SELECT ACTINDX, YEAR1, PERIODID, DEBITAMT, CRDTAMNT, PERDBLNC FROM GL10111
),
periods AS (
  SELECT YEAR1, PERIODID FROM SY40100 WHERE SERIES = 0 AND PERIODDT <= :asof_last
)
SELECT p.YEAR1 AS year, p.PERIODID AS period, RTRIM(a.ACTNUMST) AS account,
  CAST(COALESCE((SELECT SUM(PERDBLNC) FROM summ s WHERE s.ACTINDX = a.ACTINDX AND s.YEAR1 = p.YEAR1 AND s.PERIODID < p.PERIODID), 0) AS numeric(19,2)) AS beginning,
  CAST(COALESCE((SELECT SUM(DEBITAMT) FROM summ s WHERE s.ACTINDX = a.ACTINDX AND s.YEAR1 = p.YEAR1 AND s.PERIODID = p.PERIODID), 0) AS numeric(19,2)) AS debit,
  CAST(COALESCE((SELECT SUM(CRDTAMNT) FROM summ s WHERE s.ACTINDX = a.ACTINDX AND s.YEAR1 = p.YEAR1 AND s.PERIODID = p.PERIODID), 0) AS numeric(19,2)) AS credit,
  CAST(COALESCE((SELECT SUM(PERDBLNC) FROM summ s WHERE s.ACTINDX = a.ACTINDX AND s.YEAR1 = p.YEAR1 AND s.PERIODID <= p.PERIODID), 0) AS numeric(19,2)) AS ending
FROM periods p CROSS JOIN GL00105 a
ORDER BY year, period, account;

-- name: ar_aging
-- Historical aged trial balance at every period end, aged by due date.
WITH period_ends AS (
  SELECT PERDENDT AS d FROM SY40100 WHERE SERIES = 0 AND PERIODDT <= :asof_last
),
docs AS (
  SELECT CUSTNMBR, DOCNUMBR, RMDTYPAL, DOCDATE, DUEDATE, ORTRXAMT, VOIDSTTS, VOIDDATE FROM RM20101
  UNION ALL
  SELECT CUSTNMBR, DOCNUMBR, RMDTYPAL, DOCDATE, DUEDATE, ORTRXAMT, VOIDSTTS, VOIDDATE FROM RM30101
),
applies AS (
  SELECT APFRDCTY, APFRDCNM, APTODCTY, APTODCNM, APPTOAMT, DATE1 FROM RM20201
  UNION ALL
  SELECT APFRDCTY, APFRDCNM, APTODCTY, APTODCNM, APPTOAMT, DATE1 FROM RM30201
),
open_at AS (
  SELECT a.d, x.CUSTNMBR, x.RMDTYPAL, x.DUEDATE,
    CASE WHEN x.RMDTYPAL < 7
      THEN x.ORTRXAMT - COALESCE((SELECT SUM(APPTOAMT) FROM applies p WHERE p.APTODCNM = x.DOCNUMBR AND p.APTODCTY = x.RMDTYPAL AND p.DATE1 <= a.d), 0)
      ELSE -(x.ORTRXAMT - COALESCE((SELECT SUM(APPTOAMT) FROM applies p WHERE p.APFRDCNM = x.DOCNUMBR AND p.APFRDCTY = x.RMDTYPAL AND p.DATE1 <= a.d), 0))
    END AS remaining
  FROM period_ends a JOIN docs x ON x.DOCDATE <= a.d AND NOT (x.VOIDSTTS = 1 AND x.VOIDDATE <= a.d)
)
SELECT CONVERT(char(10), d, 23) AS as_of, RTRIM(CUSTNMBR) AS customer,
  CAST(SUM(CASE WHEN RMDTYPAL < 7 AND DATEDIFF(day, DUEDATE, d) <= 0 THEN remaining ELSE 0 END) AS numeric(19,2)) AS not_due,
  CAST(SUM(CASE WHEN RMDTYPAL < 7 AND DATEDIFF(day, DUEDATE, d) BETWEEN 1 AND 30 THEN remaining ELSE 0 END) AS numeric(19,2)) AS days_1_30,
  CAST(SUM(CASE WHEN RMDTYPAL < 7 AND DATEDIFF(day, DUEDATE, d) BETWEEN 31 AND 60 THEN remaining ELSE 0 END) AS numeric(19,2)) AS days_31_60,
  CAST(SUM(CASE WHEN RMDTYPAL < 7 AND DATEDIFF(day, DUEDATE, d) BETWEEN 61 AND 90 THEN remaining ELSE 0 END) AS numeric(19,2)) AS days_61_90,
  CAST(SUM(CASE WHEN RMDTYPAL < 7 AND DATEDIFF(day, DUEDATE, d) > 90 THEN remaining ELSE 0 END) AS numeric(19,2)) AS days_over_90,
  CAST(SUM(CASE WHEN RMDTYPAL >= 7 THEN remaining ELSE 0 END) AS numeric(19,2)) AS unapplied_credits,
  CAST(SUM(remaining) AS numeric(19,2)) AS balance
FROM open_at
WHERE remaining <> 0
GROUP BY d, CUSTNMBR
ORDER BY as_of, customer;

-- name: ap_aging
WITH period_ends AS (
  SELECT PERDENDT AS d FROM SY40100 WHERE SERIES = 0 AND PERIODDT <= :asof_last
),
docs AS (
  SELECT VENDORID, VCHRNMBR, DOCTYPE, DOCDATE, DUEDATE, DOCAMNT, VOIDED, VOIDPDATE FROM PM20000
  UNION ALL
  SELECT VENDORID, VCHRNMBR, DOCTYPE, DOCDATE, DUEDATE, DOCAMNT, VOIDED, VOIDPDATE FROM PM30200
),
applies AS (
  SELECT APFRDCNM, DOCTYPE, APTVCHNM, APTODCTY, APPLDAMT, DATE1 FROM PM10200
  UNION ALL
  SELECT APFRDCNM, DOCTYPE, APTVCHNM, APTODCTY, APPLDAMT, DATE1 FROM PM30300
),
open_at AS (
  SELECT a.d, x.VENDORID, x.DOCTYPE, x.DUEDATE,
    CASE WHEN x.DOCTYPE < 4
      THEN x.DOCAMNT - COALESCE((SELECT SUM(APPLDAMT) FROM applies p WHERE p.APTVCHNM = x.VCHRNMBR AND p.APTODCTY = x.DOCTYPE AND p.DATE1 <= a.d), 0)
      ELSE -(x.DOCAMNT - COALESCE((SELECT SUM(APPLDAMT) FROM applies p WHERE p.APFRDCNM = x.VCHRNMBR AND p.DOCTYPE = x.DOCTYPE AND p.DATE1 <= a.d), 0))
    END AS remaining
  FROM period_ends a JOIN docs x ON x.DOCDATE <= a.d AND NOT (x.VOIDED = 1 AND x.VOIDPDATE <= a.d)
)
SELECT CONVERT(char(10), d, 23) AS as_of, RTRIM(VENDORID) AS vendor,
  CAST(SUM(CASE WHEN DOCTYPE < 4 AND DATEDIFF(day, DUEDATE, d) <= 0 THEN remaining ELSE 0 END) AS numeric(19,2)) AS not_due,
  CAST(SUM(CASE WHEN DOCTYPE < 4 AND DATEDIFF(day, DUEDATE, d) BETWEEN 1 AND 30 THEN remaining ELSE 0 END) AS numeric(19,2)) AS days_1_30,
  CAST(SUM(CASE WHEN DOCTYPE < 4 AND DATEDIFF(day, DUEDATE, d) BETWEEN 31 AND 60 THEN remaining ELSE 0 END) AS numeric(19,2)) AS days_31_60,
  CAST(SUM(CASE WHEN DOCTYPE < 4 AND DATEDIFF(day, DUEDATE, d) BETWEEN 61 AND 90 THEN remaining ELSE 0 END) AS numeric(19,2)) AS days_61_90,
  CAST(SUM(CASE WHEN DOCTYPE < 4 AND DATEDIFF(day, DUEDATE, d) > 90 THEN remaining ELSE 0 END) AS numeric(19,2)) AS days_over_90,
  CAST(SUM(CASE WHEN DOCTYPE >= 4 THEN remaining ELSE 0 END) AS numeric(19,2)) AS unapplied_credits,
  CAST(SUM(remaining) AS numeric(19,2)) AS balance
FROM open_at
WHERE remaining <> 0
GROUP BY d, VENDORID
ORDER BY as_of, vendor;

-- name: customer_history
-- Lifetime activity per customer per year, from open and history documents.
WITH docs AS (
  SELECT CUSTNMBR, RMDTYPAL, DOCDATE, ORTRXAMT, VOIDSTTS FROM RM20101
  UNION ALL
  SELECT CUSTNMBR, RMDTYPAL, DOCDATE, ORTRXAMT, VOIDSTTS FROM RM30101
)
SELECT RTRIM(CUSTNMBR) AS customer, YEAR(DOCDATE) AS year,
  SUM(CASE WHEN RMDTYPAL = 1 THEN 1 ELSE 0 END) AS invoices,
  CAST(SUM(CASE WHEN RMDTYPAL = 1 THEN ORTRXAMT ELSE 0 END) AS numeric(19,2)) AS invoiced,
  CAST(SUM(CASE WHEN RMDTYPAL = 7 THEN ORTRXAMT ELSE 0 END) AS numeric(19,2)) AS credit_memos,
  SUM(CASE WHEN RMDTYPAL = 9 AND VOIDSTTS = 0 THEN 1 ELSE 0 END) AS payments,
  CAST(SUM(CASE WHEN RMDTYPAL = 9 AND VOIDSTTS = 0 THEN ORTRXAMT ELSE 0 END) AS numeric(19,2)) AS paid,
  SUM(CASE WHEN VOIDSTTS = 1 THEN 1 ELSE 0 END) AS voided
FROM docs
GROUP BY CUSTNMBR, YEAR(DOCDATE)
ORDER BY customer, year;

-- name: vendor_history
WITH docs AS (
  SELECT VENDORID, DOCTYPE, DOCDATE, DOCAMNT, VOIDED FROM PM20000
  UNION ALL
  SELECT VENDORID, DOCTYPE, DOCDATE, DOCAMNT, VOIDED FROM PM30200
)
SELECT RTRIM(VENDORID) AS vendor, YEAR(DOCDATE) AS year,
  SUM(CASE WHEN DOCTYPE = 1 THEN 1 ELSE 0 END) AS invoices,
  CAST(SUM(CASE WHEN DOCTYPE = 1 THEN DOCAMNT ELSE 0 END) AS numeric(19,2)) AS invoiced,
  SUM(CASE WHEN DOCTYPE = 6 AND VOIDED = 0 THEN 1 ELSE 0 END) AS payments,
  CAST(SUM(CASE WHEN DOCTYPE = 6 AND VOIDED = 0 THEN DOCAMNT ELSE 0 END) AS numeric(19,2)) AS paid,
  SUM(CASE WHEN VOIDED = 1 THEN 1 ELSE 0 END) AS voided
FROM docs
GROUP BY VENDORID, YEAR(DOCDATE)
ORDER BY vendor, year;
