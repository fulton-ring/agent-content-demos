-- Trial balance for any fiscal year and period, from the journal lines.
-- Parameters: $year, $period
WITH lines AS (
  SELECT ACTINDX, OPENYEAR AS yr, PERIODID, DEBITAMT, CRDTAMNT FROM gp.GL20000
  UNION ALL
  SELECT ACTINDX, HSTYEAR AS yr, PERIODID, DEBITAMT, CRDTAMNT FROM gp.GL30000
)
SELECT a.ACTNUMST AS account, m.ACTDESCR AS description,
  CAST(COALESCE(SUM(l.DEBITAMT - l.CRDTAMNT) FILTER (WHERE l.PERIODID < $period), 0) AS DECIMAL(19,2)) AS beginning,
  CAST(COALESCE(SUM(l.DEBITAMT) FILTER (WHERE l.PERIODID = $period), 0) AS DECIMAL(19,2)) AS debits,
  CAST(COALESCE(SUM(l.CRDTAMNT) FILTER (WHERE l.PERIODID = $period), 0) AS DECIMAL(19,2)) AS credits,
  CAST(COALESCE(SUM(l.DEBITAMT - l.CRDTAMNT) FILTER (WHERE l.PERIODID <= $period), 0) AS DECIMAL(19,2)) AS ending
FROM gp.GL00105 a
JOIN gp.GL00100 m USING (ACTINDX)
LEFT JOIN lines l ON l.ACTINDX = a.ACTINDX AND l.yr = $year
GROUP BY a.ACTNUMST, m.ACTDESCR
ORDER BY account;
