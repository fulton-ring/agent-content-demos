"""Write the run's checks and a section-by-section view of how the policies differ."""

import json
from collections.abc import Callable
from pathlib import Path

from policy_builder.checks import PolicyResult
from policy_builder.published import PdfMeasure
from policy_builder.review import ReviewRecord
from policy_builder.schema import Policy

CHECK_COLUMNS: list[tuple[str, Callable[[PolicyResult], object]]] = [
    ("Policy", lambda r: r.organization),
    ("First draft fill", lambda r: r.run.first_draft_fill),
    ("Shorten passes", lambda r: r.run.shorten_passes),
    ("Pages", lambda r: r.pages),
    ("Page fill", lambda r: r.page_fill),
    ("Words", lambda r: r.words),
    ("FK grade", lambda r: r.flesch_kincaid_grade),
    ("Reading ease", lambda r: r.flesch_reading_ease),
    ("Sections filled", lambda r: f"{r.sections_filled}/{r.sections_total}"),
    ("Open questions", lambda r: r.open_questions),
    ("Names not in call", lambda r: ", ".join(r.untraced_names) or "none"),
    ("Draft calls", lambda r: r.run.draft.model_calls),
    ("Draft seconds", lambda r: r.run.draft.seconds),
    ("Draft cost (USD)", lambda r: r.run.draft.cost_usd),
    ("Check calls", lambda r: r.run.check.model_calls),
    ("Check seconds", lambda r: r.run.check.seconds),
    ("Check cost (USD)", lambda r: r.run.check.cost_usd),
]

FIDELITY_HEADER = ["Policy", "Pass", "Statements", "Supported", "Default", "Unsupported", "Contradicts", "Missed"]


def fidelity_rows(result: PolicyResult) -> list[list[str]]:
    passes = [("first draft", result.fidelity_first)]
    if result.run.revise_passes:
        passes.append(("after revise", result.fidelity_final))
    return [[result.organization, name, *(str(n) for n in counts.model_dump().values())] for name, counts in passes]


def problem_report(policies: list[tuple[str, ReviewRecord]]) -> str:
    """Every unsupported or contradicting statement and every miss, before and after the revise pass."""
    parts = ["# Fidelity check findings\n", "Generated by `uv run build-policies` from `output/*/review.json`.\n"]
    for organization, record in policies:
        parts.append(f"## {organization}\n")
        for name, review in [("First draft", record.first), ("Final", record.final)]:
            parts.append(f"**{name}**\n")
            parts.extend(f'- {s.label} ({s.section}): "{s.statement}" {s.reason}' for s in review.problems())
            parts.extend(f"- missed: {m}" for m in review.missed)
            parts.append("")
    return "\n".join(parts)


COMPARED_SECTIONS: list[tuple[str, str]] = [
    ("Tools we use", "tools"),
    ("Everyone, now", "everyone_now"),
    ("Needs approval first", "needs_approval"),
    ("Never put into an AI tool", "protected_information"),
    ("Off limits", "off_limits"),
    ("Decisions about people", "decisions_about_people"),
    ("Being open about AI", "being_open"),
    ("Open questions for the board", "open_questions"),
]


def check_row(result: PolicyResult) -> list[str]:
    return [str(cell(result)) for _, cell in CHECK_COLUMNS]


def markdown_table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(r) + " |" for r in rows])


def section_lines(policy: Policy, field: str) -> list[str]:
    value = getattr(policy, field)
    if field == "tools":
        return [f"**{t.name}**: {t.approved_for}" for t in policy.tools]
    if field == "needs_approval":
        return [f"{r.use} ({r.approver})" for r in policy.needs_approval]
    return [value] if isinstance(value, str) else list(value)


def side_by_side(policies: list[Policy]) -> str:
    parts = ["# How the policies differ\n", "Generated by `uv run build-policies` from `output/*/policy.json`.\n"]
    for title, field in COMPARED_SECTIONS:
        parts.append(f"## {title}\n")
        for policy in policies:
            parts.append(f"**{policy.organization}**\n")
            parts.extend(f"- {line}" for line in section_lines(policy, field))
            parts.append("")
    return "\n".join(parts)


def write_reports(output: Path, built: list[tuple[Policy, PolicyResult, ReviewRecord]]) -> None:
    policies, results = [p for p, _, _ in built], [r for _, r, _ in built]
    (output / "checks.json").write_text(json.dumps([r.model_dump() for r in results], indent=2) + "\n")
    table = markdown_table([h for h, _ in CHECK_COLUMNS], [check_row(r) for r in results])
    fidelity = markdown_table(FIDELITY_HEADER, [row for r in results for row in fidelity_rows(r)])
    (output / "checks.md").write_text(
        f"# Checks\n\nGenerated by `uv run build-policies`.\n\n{table}\n\n## Fidelity check\n\n{fidelity}\n"
    )
    (output / "side-by-side.md").write_text(side_by_side(policies))
    (output / "fidelity-findings.md").write_text(problem_report([(p.organization, rv) for p, _, rv in built]))
    print(table)
    print(fidelity)


def write_published(output: Path, measures: list[PdfMeasure]) -> None:
    (output / "published-comparison.json").write_text(json.dumps([m.model_dump() for m in measures], indent=2) + "\n")
    header = ["Document", "Pages", "Words", "FK grade", "Reading ease"]
    rows = [
        [m.document, str(m.pages), str(m.words), str(m.flesch_kincaid_grade), str(m.flesch_reading_ease)]
        for m in measures
    ]
    table = markdown_table(header, rows)
    note = "Every row is scored the same way: text extracted from the PDF with pypdf, then textstat."
    (output / "published-comparison.md").write_text(
        f"# Length and reading level against published policies\n\n{note}\n\n{table}\n"
    )
    print(table)
